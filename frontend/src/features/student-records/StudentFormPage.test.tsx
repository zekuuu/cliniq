import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter, Route, Routes } from 'react-router'
import { beforeEach, describe, expect, it } from 'vitest'
import { getRecordedAuditEntries, getStudent, LrnLockedError, NameCorrectionReasonError, resetMockDb, saveStudent } from '../../lib/mock-db'
import { selectOption } from '../../test/selectOption'
import { paths } from '../../routes/paths'
import { StudentFormPage } from './StudentFormPage'
import { StudentProfilePage } from './StudentProfilePage'
import { fetchStudentList } from './api/studentListApi'
import { renderWithRouter } from '../../test/renderWithRouter'

async function fillRequiredStudentFields() {
  const user = userEvent.setup()
  await user.type(screen.getByLabelText(/^LRN/), '1234 5678-9012')
  await user.type(screen.getByLabelText(/full name/i), 'Lara Santos')
  await selectOption(user, screen.getByLabelText(/grade level/i), 'Grade 6')
  await selectOption(user, screen.getByLabelText(/^sex/i), 'Female')
  await user.type(screen.getByLabelText(/contact name/i), 'Marisol Santos')
  await user.type(screen.getByLabelText(/relationship/i), 'Mother')
  await user.type(screen.getByLabelText(/contact phone/i), '0917-333-4444')
  await user.type(screen.getByLabelText(/allergies/i), 'None')
  await user.type(screen.getByLabelText(/medical conditions/i), 'None')
  return user
}

describe('Student Form', () => {
  beforeEach(() => {
    resetMockDb()
  })

  it('asks for the LRN in add mode; nothing is generated by the system (ADR-028)', async () => {
    renderWithRouter(<StudentFormPage />)

    expect(await screen.findByRole('heading', { name: 'Add Student' })).toBeInTheDocument()
    expect(screen.getByLabelText(/^LRN/)).toHaveValue('')
    expect(screen.queryByLabelText(/student number/i)).not.toBeInTheDocument()
  })

  it('uses standard-height dropdowns beside the student information inputs', async () => {
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })

    expect(screen.getByLabelText(/grade level/i)).toHaveClass('h-10')
    expect(screen.getByLabelText(/^sex/i)).toHaveClass('h-10')
  })

  it('omits redundant add/edit and staff-access badges', async () => {
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })

    expect(screen.queryByText('New record')).not.toBeInTheDocument()
    expect(screen.queryByText('Editing existing')).not.toBeInTheDocument()
    expect(screen.queryByText('Staff only')).not.toBeInTheDocument()
  })

  it('keeps only digits in the LRN and requires exactly 12', async () => {
    const user = userEvent.setup()
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })
    const lrn = screen.getByLabelText(/^LRN/)
    await user.click(screen.getByRole('button', { name: 'Save Student' }))
    expect(screen.getByText('Enter the 12-digit LRN.')).toBeInTheDocument()
    await user.type(lrn, '0123 4567-89')
    expect(lrn).toHaveValue('0123456789')
    await user.click(screen.getByRole('button', { name: 'Save Student' }))
    expect(screen.getByText('The LRN must be exactly 12 digits.')).toBeInTheDocument()
  })

  it('refuses an LRN another student already has, without naming that student', async () => {
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage />)
    await screen.findByRole('heading', { name: 'Add Student' })
    const user = await fillRequiredStudentFields()
    await user.clear(screen.getByLabelText(/^LRN/))
    await user.type(screen.getByLabelText(/^LRN/), existing.lrn)
    await user.click(screen.getByRole('button', { name: 'Save Student' }))

    expect(await screen.findByText('This LRN is already used by another student record.')).toBeInTheDocument()
    expect(document.body.textContent).not.toContain(existing.fullName)
    expect(getRecordedAuditEntries()).toEqual([])
  })

  it('says while typing that an LRN is taken or a name is already listed, before any save', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage />)
    await screen.findByRole('heading', { name: 'Add Student' })

    await user.type(screen.getByLabelText(/^LRN/), existing.lrn)
    expect(await screen.findByText('This LRN is already used by another student record.')).toBeInTheDocument()
    expect(document.body.textContent).not.toContain(existing.fullName)

    await user.type(screen.getByLabelText(/full name/i), existing.fullName)
    const note = await screen.findByText('Already in the Student List:')
    expect(note.parentElement).toHaveTextContent(existing.gradeLevel)
    expect(note.parentElement).toHaveTextContent(existing.lrn.slice(-4))
    expect(getRecordedAuditEntries()).toEqual([])
  })

  it('suggests None recorded when Allergies or Medical conditions is focused (ADR-051)', async () => {
    const user = userEvent.setup()
    renderWithRouter(<StudentFormPage />)
    await screen.findByRole('heading', { name: 'Add Student' })
    await user.click(screen.getByRole('combobox', { name: /^Allergies/ }))
    await user.click(await screen.findByRole('option', { name: 'None recorded' }))
    expect(screen.getByRole('combobox', { name: /^Allergies/ })).toHaveValue('None recorded')

    await user.type(screen.getByRole('combobox', { name: /^Medical conditions/ }), 'Asthma')
    expect(screen.queryByRole('option', { name: 'None recorded' })).not.toBeInTheDocument()
  })

  it('locks the LRN on Edit Student, in the form and in the data layer (ADR-028, Sir Rey)', async () => {
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage studentId={existing.id} />)

    await screen.findByRole('heading', { name: 'Edit Student' })
    const lrn = screen.getByLabelText(/^LRN/)
    expect(lrn).toHaveValue(existing.lrn)
    expect(lrn).toHaveAttribute('readonly')
    expect(lrn).toHaveAccessibleDescription("The LRN is the student's identifier and can't be changed.")

    const full = await getStudent(existing.id)
    await expect(saveStudent({ ...full, lrn: '987654321098' }, { studentId: existing.id })).rejects.toBeInstanceOf(LrnLockedError)
    expect((await getStudent(existing.id)).lrn).toBe(existing.lrn)
    expect(getRecordedAuditEntries()).toHaveLength(0)
  })

  it('asks for a reason before saving a name correction, and audits the reason without the names', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage studentId={existing.id} />)

    await screen.findByRole('heading', { name: 'Edit Student' })
    expect(screen.queryByLabelText(/^Reason for the name correction/)).not.toBeInTheDocument()
    await user.clear(screen.getByLabelText(/^Full name/))
    await user.type(screen.getByLabelText(/^Full name/), 'Corrected Surname')
    await user.click(screen.getByRole('button', { name: 'Save Changes' }))
    const reason = screen.getByLabelText(/^Reason for the name correction/)
    expect(reason).toHaveAccessibleDescription(expect.stringMatching(/Enter why the name is being corrected/))
    expect(reason).toHaveFocus()
    expect(getRecordedAuditEntries()).toHaveLength(0)

    const full = await getStudent(existing.id)
    await expect(saveStudent({ ...full, fullName: 'Corrected Surname' }, { studentId: existing.id, nameCorrectionReason: 'ok' })).rejects.toBeInstanceOf(NameCorrectionReasonError)

    await user.type(reason, 'Misspelled on the enrolment form')
    await user.click(screen.getByRole('button', { name: 'Save Changes' }))
    await waitFor(() => expect(getRecordedAuditEntries()).toHaveLength(1))
    expect(getRecordedAuditEntries()[0]).toMatchObject({
      actionType: 'update',
      summary: 'Updated name. Name corrected; reason: Misspelled on the enrolment form',
    })
    expect(JSON.stringify(getRecordedAuditEntries())).not.toMatch(new RegExp(`Corrected Surname|${existing.fullName}`))
    expect((await getStudent(existing.id)).fullName).toBe('Corrected Surname')
  })

  it('validates required fields inline', async () => {
    const user = userEvent.setup()
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })
    await user.click(screen.getByRole('button', { name: 'Save Student' }))

    expect(screen.getByText('Enter the student full name.')).toBeInTheDocument()
    expect(screen.getByText('Select the grade level.')).toBeInTheDocument()
    expect(screen.getByText('Select the sex recorded by the school.')).toBeInTheDocument()
    // Allergies and conditions may be left empty; an empty field reads "None recorded" (ADR-051).
    expect(screen.queryByText(/Enter allergies/)).not.toBeInTheDocument()
    expect(screen.queryByText(/Enter medical conditions/)).not.toBeInTheDocument()
  })

  it('warns before creating a possible duplicate and records the confirmed create', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({
      search: '',
      gradeLevel: '',
      includeArchived: false,
    })
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })
    await user.type(screen.getByLabelText(/^LRN/), '123456789012')
    await user.type(screen.getByLabelText(/full name/i), existing.fullName)
    await selectOption(user, screen.getByLabelText(/grade level/i), existing.gradeLevel)
    await selectOption(user, screen.getByLabelText(/^sex/i), 'Female')
    await user.type(screen.getByLabelText(/contact name/i), 'Parent Guardian')
    await user.type(screen.getByLabelText(/relationship/i), 'Parent')
    await user.type(screen.getByLabelText(/contact phone/i), '0917-333-4444')
    await user.type(screen.getByLabelText(/allergies/i), 'None')
    await user.type(screen.getByLabelText(/medical conditions/i), 'None')
    await user.click(screen.getByRole('button', { name: 'Save Student' }))

    const dialog = await screen.findByRole('dialog', { name: 'Possible duplicate record' })
    expect(dialog).toBeInTheDocument()
    expect(within(dialog).getAllByText(existing.fullName).length).toBeGreaterThan(0)

    await user.click(screen.getByRole('button', { name: 'Confirm Create' }))
    expect(await screen.findByText(/student record created/i)).toBeInTheDocument()
    expect(getRecordedAuditEntries().map((entry) => entry.actionType)).toEqual(['create'])
  })

  it('saves a non-duplicate new student', async () => {
    renderWithRouter(<StudentFormPage />)
    await screen.findByRole('heading', { name: 'Add Student' })
    const user = await fillRequiredStudentFields()

    await user.click(screen.getByRole('button', { name: 'Save Student' }))

    expect(await screen.findByText('Student record created for Lara Santos.')).toBeInTheDocument()
    expect(getRecordedAuditEntries().map((entry) => entry.actionType)).toEqual(['create'])
    // The form is cleared for the next student.
    expect(screen.getByLabelText(/full name/i)).toHaveValue('')
  })

  it('adds, promotes, and removes repeatable emergency contacts', async () => {
    renderWithRouter(<StudentFormPage />)
    await screen.findByRole('heading', { name: 'Add Student' })
    const user = await fillRequiredStudentFields()

    await user.click(screen.getByRole('button', { name: 'Add another contact' }))
    await user.type(screen.getByLabelText('Emergency contact 2 name'), 'Bea Santos')
    await user.type(screen.getByLabelText('Emergency contact 2 relationship'), 'Sister or brother')
    await user.type(screen.getByLabelText('Emergency contact 2 phone'), '0917-333-5555')
    await user.click(screen.getByRole('button', { name: 'Make primary' }))

    expect(screen.getByLabelText(/Primary emergency contact name/)).toHaveValue('Bea Santos')
    expect(screen.getByLabelText('Emergency contact 2 name')).toHaveValue('Marisol Santos')

    await user.click(screen.getAllByRole('button', { name: 'Remove contact' })[1])
    expect(screen.queryByLabelText('Emergency contact 2 name')).not.toBeInTheDocument()
  })

  it('supports edit mode, records an update audit entry, and returns to the profile', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    render(
      <MemoryRouter initialEntries={[paths.studentEdit(existing.id)]}>
        <Routes>
          <Route
            path="/students/:studentId/edit"
            element={<StudentFormPage studentId={existing.id} />}
          />
          <Route
            path="/students/:studentId"
            element={<StudentProfilePage studentId={existing.id} />}
          />
        </Routes>
      </MemoryRouter>,
    )

    expect(await screen.findByRole('heading', { name: 'Edit Student' })).toBeInTheDocument()
    await user.type(screen.getByLabelText(/contact name/i), ' Jr')
    await user.click(screen.getByRole('button', { name: 'Save Changes' }))

    expect(await screen.findByText(`Student record updated for ${existing.fullName}.`)).toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'Edit Student' })).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: existing.fullName })).toBeInTheDocument()
    expect(getRecordedAuditEntries().map((entry) => entry.actionType)).toContain('update')
  })

  it('rejects an emergency contact phone with letters, in plain words', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage studentId={existing.id} />)

    await screen.findByRole('heading', { name: 'Edit Student' })
    await user.clear(screen.getByLabelText(/contact phone/i))
    await user.type(screen.getByLabelText(/contact phone/i), '89r91r91r')
    await user.click(screen.getByRole('button', { name: 'Save Changes' }))

    expect(screen.getByText(/Enter a Philippine mobile number/)).toBeInTheDocument()
    expect(screen.getByLabelText(/contact phone/i)).toHaveFocus()
    expect(getRecordedAuditEntries()).toEqual([])
  })

  it('moves focus to the first invalid field and announces the count after a failed save', async () => {
    const user = userEvent.setup()
    renderWithRouter(<StudentFormPage />)

    await screen.findByRole('heading', { name: 'Add Student' })
    await user.type(screen.getByLabelText(/full name/i), 'Lara Santos')
    await user.click(screen.getByRole('button', { name: 'Save Student' }))

    expect(screen.getByLabelText(/^LRN/)).toHaveFocus()
    // Allergies and conditions are optional now (ADR-051), so two fewer than before.
    expect(screen.getByText('6 fields need attention.')).toBeInTheDocument()
  })

  it('requires Sex and audits an edit to it without storing a value in the audit summary', async () => {
    const user = userEvent.setup()
    const [existing] = await fetchStudentList({ search: '', gradeLevel: '', includeArchived: false })
    renderWithRouter(<StudentFormPage studentId={existing.id} />)

    await screen.findByRole('heading', { name: 'Edit Student' })
    const sex = screen.getByLabelText(/^sex/i)
    await user.click(sex)
    await user.click(screen.getByRole('option', { name: existing.sex === 'female' ? 'Male' : 'Female' }))
    await user.click(screen.getByRole('button', { name: 'Save Changes' }))

    const entry = getRecordedAuditEntries().at(-1)
    expect(entry).toMatchObject({ actionType: 'update', targetRecord: { type: 'student', id: existing.id }, summary: 'Updated sex' })
    expect(entry?.summary).not.toContain(existing.sex)
  })
})
